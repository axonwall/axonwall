import type { RosenpassConfig } from '../../schemas/index.js';

export interface RosenpassCompileResult {
  configToml: string;
  systemdUnit: string;
}

function sanitizeTomlString(input: string): string {
  return input.replace(/[\r\n"\\]+/g, '').trim();
}

export function compileRosenpass(config?: RosenpassConfig): RosenpassCompileResult {
  const lines: string[] = [];

  const listenPort = config?.listenPort && config.listenPort >= 1 && config.listenPort <= 65535 ? config.listenPort : 9999;
  const rawListen =
    config?.listenAddresses && config.listenAddresses.length > 0
      ? config.listenAddresses
      : [`0.0.0.0:${listenPort}`, `[::]:${listenPort}`];
  const listenList = rawListen
    .map((addr) => sanitizeTomlString(addr))
    .filter(Boolean)
    .map((addr) => `"${addr}"`)
    .join(', ');

  const pubKeyPath = sanitizeTomlString(config?.publicKeyPath || '/etc/rosenpass/pq.pk');
  const secKeyPath = sanitizeTomlString(config?.secretKeyPath || '/etc/rosenpass/pq.sk');
  const verbosity = config?.verbosity === 'Verbose' ? 'Verbose' : 'Quiet';
  const defaultWgDevice = sanitizeTomlString(config?.wgDevice || 'wg0') || 'wg0';

  lines.push('# Axonwall Rosenpass Post-Quantum Hybrid Dual-KEM Configuration');
  lines.push('# Primitives: Classic McEliece 460896 (Static KEM Auth) + ML-KEM-512 / Kyber-512 (Ephemeral Forward Secrecy)');
  lines.push('# Auto-generated by @axonwall/lib — DO NOT EDIT MANUALLY');
  lines.push('');
  lines.push(`public_key = "${pubKeyPath}"`);
  lines.push(`secret_key = "${secKeyPath}"`);
  lines.push(`listen = [${listenList}]`);
  lines.push(`verbosity = "${verbosity}"`);
  lines.push('');

  const peers = config?.peers ?? [];
  for (const peer of peers) {
    if (!peer.enabled) continue;
    const safeName = peer.name.replace(/[^a-zA-Z0-9_-]/g, '');
    const peerPubPath = sanitizeTomlString(
      peer.pqPublicKeyPath || `/etc/rosenpass/peers/${safeName || 'peer'}-pq.pk`,
    );
    const wgPeerKey = sanitizeTomlString(peer.wgPeerPublicKey);
    if (!wgPeerKey) continue;
    const wgDev = sanitizeTomlString(peer.wgDevice || defaultWgDevice) || defaultWgDevice;

    lines.push(`# Peer: ${safeName || 'unnamed'}${peer.pqPublicKeySha256 ? ` (SHA-256: ${sanitizeTomlString(peer.pqPublicKeySha256).slice(0, 16)}...)` : ''}`);
    lines.push('[[peers]]');
    lines.push(`public_key = "${peerPubPath}"`);
    if (peer.endpoint && sanitizeTomlString(peer.endpoint)) {
      lines.push(`endpoint = "${sanitizeTomlString(peer.endpoint)}"`);
    }
    if (peer.keyOut && sanitizeTomlString(peer.keyOut)) {
      lines.push(`key_out = "${sanitizeTomlString(peer.keyOut)}"`);
    } else {
      lines.push(`wg_device = "${wgDev}"`);
      lines.push(`wg_peer = "${wgPeerKey}"`);
    }
    lines.push('');
  }

  const systemdUnit = [
    '[Unit]',
    'Description=Rosenpass Post-Quantum Hybrid Dual-KEM Key Exchange Daemon (Axonwall)',
    'Documentation=https://rosenpass.eu/',
    `After=network-online.target wg-quick@${defaultWgDevice}.service`,
    'Wants=network-online.target',
    '',
    '[Service]',
    'Type=simple',
    'ExecStart=/usr/bin/rosenpass exchange-config /etc/rosenpass/config.toml',
    'Restart=on-failure',
    'RestartSec=5s',
    'CapabilityBoundingSet=CAP_NET_ADMIN',
    'AmbientCapabilities=CAP_NET_ADMIN',
    'NoNewPrivileges=true',
    'PrivateTmp=true',
    'ProtectHome=true',
    'ProtectSystem=strict',
    'ReadWritePaths=/etc/rosenpass /run',
    'LockPersonality=true',
    'MemoryDenyWriteExecute=true',
    '',
    '[Install]',
    'WantedBy=multi-user.target',
    '',
  ].join('\n');

  return {
    configToml: lines.join('\n'),
    systemdUnit,
  };
}
