import type { WireGuardConfigSchema } from '../../schemas/index.js';
import { z } from 'zod';

type WireGuardConfig = z.infer<typeof WireGuardConfigSchema>;

export interface WireGuardCompileResult {
  wgConfig: string;
}

export function compileWireGuard(wg: WireGuardConfig): WireGuardCompileResult {
  const lines: string[] = [];

  lines.push('# Axonwall WireGuard Server Configuration');
  lines.push('# Auto-generated by @axonwall/lib');
  lines.push('');
  lines.push('[Interface]');
  lines.push(`Address = ${wg.address}`);
  lines.push(`ListenPort = ${wg.listenPort}`);
  if (wg.privateKey) {
    lines.push(`PrivateKey = ${wg.privateKey}`);
  }
  lines.push('');

  for (const peer of wg.peers) {
    if (!peer.enabled) continue;
    lines.push('# Peer: ' + peer.name);
    lines.push('[Peer]');
    lines.push(`PublicKey = ${peer.publicKey}`);
    if (peer.presharedKey) {
      lines.push(`PresharedKey = ${peer.presharedKey}`);
    }
    lines.push(`AllowedIPs = ${peer.allowedIps.join(', ')}`);
    if (peer.endpoint) {
      lines.push(`Endpoint = ${peer.endpoint}`);
    }
    if (peer.persistentKeepalive > 0) {
      lines.push(`PersistentKeepalive = ${peer.persistentKeepalive}`);
    }
    lines.push('');
  }

  return {
    wgConfig: lines.join('\n'),
  };
}
